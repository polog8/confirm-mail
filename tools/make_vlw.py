#!/usr/bin/env python3
"""Renders a TrueType font into an anti-aliased VLW font (the "smooth font"
format understood by LovyanGFX / M5GFX `loadFont()`), emitted as a C header.

    python3 tools/make_vlw.py FONT.ttf SIZE_PX SYMBOL OUT.h [--chars digits|latin]

VLW layout (all integers 32-bit big-endian):
    header : glyph_count, version(11), size, 0, ascent, descent
    glyphs : (unicode, height, width, x_advance, dY, dX, 0) * glyph_count
    bitmaps: width*height alpha bytes per glyph, same order (sorted by unicode)
dY is the distance from the baseline up to the top of the bitmap.
"""
import argparse
import struct

from fontTools.ttLib import TTFont
from PIL import Image, ImageFont

EXTRA = [
    0x2009, 0x202F, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026,
    0x2032, 0x2039, 0x203A, 0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212,
    0x2264, 0x2265, 0x221E, 0x2713, 0x25B6, 0x25CF, 0x2661, 0x2665, 0x266A, 0x266B,
]


def charset(kind, cmap):
    if kind == "digits":
        cps = [ord(c) for c in " 0123456789:+-−°%"]
    else:
        cps = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + EXTRA
    return sorted({c for c in cps if c in cmap or c == 0x20})


def render(font_path, size, kind):
    cmap = TTFont(font_path).getBestCmap()
    font = ImageFont.truetype(font_path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for cp in charset(kind, cmap):
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        if ch.isspace():
            glyphs.append((cp, 0, 0, adv, 0, 0, b""))
            continue
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        img = Image.frombytes("L", mask.size, bytes(mask)) if mask.size[0] and mask.size[1] else None
        bbox = img.getbbox() if img else None
        if not bbox:
            glyphs.append((cp, 0, 0, adv, 0, 0, b""))
            continue
        img = img.crop(bbox)
        w, h = img.size
        dx = ox + bbox[0]
        dy = -(oy + bbox[1])
        if w > 255 or adv > 255 or not -128 <= dx <= 127:
            raise SystemExit(f"glyph U+{cp:04X} too large for VLW ({w}x{h}, adv {adv}, dx {dx})")
        glyphs.append((cp, h, w, adv, dy, dx, img.tobytes()))
    return glyphs, ascent, descent


def build_vlw(glyphs, size, ascent, descent):
    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for cp, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for *_, bmp in glyphs:
        out += bmp
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("font")
    ap.add_argument("size", type=int)
    ap.add_argument("symbol")
    ap.add_argument("out")
    ap.add_argument("--chars", default="latin", choices=["latin", "digits"])
    args = ap.parse_args()

    glyphs, ascent, descent = render(args.font, args.size, args.chars)
    data = build_vlw(glyphs, args.size, ascent, descent)
    with open(args.out, "w") as f:
        f.write("// Generated by tools/make_vlw.py -- do not edit.\n")
        f.write(f"// Source: {args.font.split('/')[-1]} @ {args.size}px, {len(glyphs)} glyphs, "
                f"{len(data)} bytes. Inter is licensed under the SIL OFL 1.1.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"alignas(4) static const uint8_t {args.symbol}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
    print(f"{args.out}: {len(glyphs)} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    main()
